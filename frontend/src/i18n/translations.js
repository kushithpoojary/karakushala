/**
 * Format template strings with params
 */
export function formatTemplate(templateStr, params = {}) {
  if (!templateStr) return '';
  return Object.keys(params).reduce((str, key) => {
    return str.replace(new RegExp(`\\{${key}\\}`, 'g'), params[key]);
  }, templateStr);
}

/**
 * Get translation for a key in a specified language
 */
export function getTranslation(key, langCode = 'en-IN', params = {}) {
  const langKey = (langCode || 'en-IN').split('-')[0].toLowerCase();
  const dict = TRANSLATIONS[langKey] || TRANSLATIONS.en;
  const message = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key);
  return formatTemplate(message, params);
}
